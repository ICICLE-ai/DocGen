// Swap freshly generated output into place without ever leaving a half-written site.
//
// Ingest writes everything into a staging folder first. commitStage then:
//   1. refuses up front if a target exists that DocGen did not generate (hand-written);
//   2. moves the output being replaced into a backup folder (rename: atomic per path);
//   3. moves each staged entry into place;
//   4. on any error, undoes 3 and 2 in reverse order, so the previous output is restored.
// Renames stay on one file system (everything lives under site/), so each step is atomic.

import fs from 'node:fs';
import path from 'node:path';

/**
 * @param {object} o
 * @param {string[]} o.retire     existing generated paths to replace or remove
 * @param {[string, string][]} o.installs  [stagedPath, finalPath] pairs
 * @param {string} o.backupDir    scratch folder for the previous output
 * @param {(from: string, to: string) => void} [o.rename]  injectable for tests
 */
export function commitStage({ retire, installs, backupDir, rename = fs.renameSync }) {
  const retiring = new Set(retire.map((p) => path.resolve(p)));
  // A target is replaceable if it, or a folder containing it, is being retired.
  const covered = (dst) => {
    for (let p = path.resolve(dst); ; p = path.dirname(p)) {
      if (retiring.has(p)) return true;
      if (path.dirname(p) === p) return false;
    }
  };
  for (const [, dst] of installs) {
    if (fs.existsSync(dst) && !covered(dst)) {
      throw new Error(`refusing to overwrite ${dst}: it was not generated by DocGen. Rename or remove it, then re-run.`);
    }
  }

  fs.rmSync(backupDir, { recursive: true, force: true });
  const moved = [];
  const installed = [];
  try {
    for (const p of retire) {
      if (!fs.existsSync(p)) continue;
      fs.mkdirSync(backupDir, { recursive: true });
      const b = path.join(backupDir, String(moved.length));
      rename(p, b);
      moved.push([p, b]);
    }
    for (const [src, dst] of installs) {
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      rename(src, dst);
      installed.push([src, dst]);
    }
  } catch (e) {
    for (const [src, dst] of installed.reverse()) {
      try {
        fs.renameSync(dst, src);
      } catch {
        fs.rmSync(dst, { recursive: true, force: true });
      }
    }
    for (const [p, b] of moved.reverse()) {
      fs.rmSync(p, { recursive: true, force: true });
      fs.mkdirSync(path.dirname(p), { recursive: true });
      fs.renameSync(b, p);
    }
    fs.rmSync(backupDir, { recursive: true, force: true });
    throw new Error(`could not install the new output (${e.message}); the previous output was restored`);
  }
  fs.rmSync(backupDir, { recursive: true, force: true });
}
